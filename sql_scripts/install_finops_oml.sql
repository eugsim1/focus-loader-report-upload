PROMPT Creating monthly cost and feature views...
CREATE OR REPLACE VIEW FOCUS_OML_DIM_MONTHLY AS
SELECT
  DIMENSION_TYPE,
  DIMENSION_VALUE,
  COST_MONTH,
  BILLING_CURRENCY,
  SUM(EFFECTIVE_COST) AS EFFECTIVE_COST,
  SUM(ROW_COUNT) AS ROW_COUNT
FROM (
  SELECT
    'TOTAL' AS DIMENSION_TYPE,
    '(all costs)' AS DIMENSION_VALUE,
    TRUNC(CHARGE_PERIOD_START, 'MM') AS COST_MONTH,
    NVL(TRIM(BILLING_CURRENCY), '(not provided)') AS BILLING_CURRENCY,
    NVL(EFFECTIVE_COST, 0) AS EFFECTIVE_COST,
    1 AS ROW_COUNT
  FROM TEMP_OCI_FOCUS
  WHERE CHARGE_PERIOD_START IS NOT NULL

  UNION ALL

  SELECT
    'SERVICE',
    NVL(TRIM(SERVICE_NAME), '(unassigned)'),
    TRUNC(CHARGE_PERIOD_START, 'MM'),
    NVL(TRIM(BILLING_CURRENCY), '(not provided)'),
    NVL(EFFECTIVE_COST, 0),
    1
  FROM TEMP_OCI_FOCUS
  WHERE CHARGE_PERIOD_START IS NOT NULL

  UNION ALL

  SELECT
    'REGION',
    NVL(TRIM(REGION_NAME), NVL(TRIM(REGION_ID), '(unassigned)')),
    TRUNC(CHARGE_PERIOD_START, 'MM'),
    NVL(TRIM(BILLING_CURRENCY), '(not provided)'),
    NVL(EFFECTIVE_COST, 0),
    1
  FROM TEMP_OCI_FOCUS
  WHERE CHARGE_PERIOD_START IS NOT NULL

  UNION ALL

  SELECT
    'CREATEDBY',
    COALESCE(
      NULLIF(TRIM(TAG_SPECIAL1), ''),
      NULLIF(TRIM(TAG_SPECIAL3), ''),
      '(unassigned)'
    ),
    TRUNC(CHARGE_PERIOD_START, 'MM'),
    NVL(TRIM(BILLING_CURRENCY), '(not provided)'),
    NVL(EFFECTIVE_COST, 0),
    1
  FROM TEMP_OCI_FOCUS
  WHERE CHARGE_PERIOD_START IS NOT NULL
)
GROUP BY DIMENSION_TYPE, DIMENSION_VALUE, COST_MONTH, BILLING_CURRENCY;

CREATE OR REPLACE VIEW FOCUS_OML_TOTAL_FEATURES AS
WITH LAGGED AS (
  SELECT
    DIMENSION_VALUE,
    BILLING_CURRENCY,
    COST_MONTH,
    EFFECTIVE_COST,
    ROW_COUNT,
    LAG(EFFECTIVE_COST) OVER (
      PARTITION BY DIMENSION_VALUE, BILLING_CURRENCY ORDER BY COST_MONTH
    ) AS PREVIOUS_COST,
    AVG(EFFECTIVE_COST) OVER (
      PARTITION BY DIMENSION_VALUE, BILLING_CURRENCY ORDER BY COST_MONTH
      ROWS BETWEEN 2 PRECEDING AND CURRENT ROW
    ) AS MOVING_AVG_3
  FROM FOCUS_OML_DIM_MONTHLY
  WHERE DIMENSION_TYPE = 'TOTAL'
)
SELECT
  ROW_NUMBER() OVER (
    ORDER BY DIMENSION_VALUE, BILLING_CURRENCY, COST_MONTH
  ) AS CASE_ID,
  DIMENSION_VALUE,
  BILLING_CURRENCY,
  TO_NUMBER(TO_CHAR(COST_MONTH, 'YYYYMM')) AS MONTH_KEY,
  TO_NUMBER(TO_CHAR(COST_MONTH, 'MM')) AS MONTH_NUMBER,
  EFFECTIVE_COST,
  NVL(PREVIOUS_COST, EFFECTIVE_COST) AS PREVIOUS_COST,
  MOVING_AVG_3,
  CASE
    WHEN NVL(ABS(PREVIOUS_COST), 0) = 0 THEN 0
    ELSE (EFFECTIVE_COST - PREVIOUS_COST) / ABS(PREVIOUS_COST)
  END AS CHANGE_RATIO,
  ROW_COUNT
FROM LAGGED;

