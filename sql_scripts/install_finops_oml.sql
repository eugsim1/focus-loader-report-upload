-- Install optional OML4SQL analytics for TEMP_OCI_FOCUS in the current schema.
-- Run as the application schema owner. Required direct privilege:
--   GRANT CREATE MINING MODEL TO <schema>;
-- The script is idempotent for its FOCUS_OML_* tables, views, and package.

WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
SET DEFINE OFF
SET SERVEROUTPUT ON SIZE UNLIMITED

PROMPT Checking TEMP_OCI_FOCUS and OML privileges...
DECLARE
  l_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO l_count
  FROM USER_TABLES
  WHERE TABLE_NAME = 'TEMP_OCI_FOCUS';

  IF l_count = 0 THEN
    RAISE_APPLICATION_ERROR(-20001, 'TEMP_OCI_FOCUS does not exist in the current schema');
  END IF;

  SELECT COUNT(*) INTO l_count
  FROM USER_SYS_PRIVS
  WHERE PRIVILEGE = 'CREATE MINING MODEL';

  IF l_count = 0 THEN
    RAISE_APPLICATION_ERROR(
      -20002,
      'CREATE MINING MODEL must be granted directly to the current schema'
    );
  END IF;
END;
