DECLARE
  PROCEDURE create_if_missing(p_sql IN VARCHAR2) IS
  BEGIN
    EXECUTE IMMEDIATE p_sql;
  EXCEPTION
    WHEN OTHERS THEN
      IF SQLCODE != -955 THEN
        RAISE;
      END IF;
  END;
BEGIN
  create_if_missing(q'[
    CREATE TABLE FOCUS_OML_RUNS (
      RUN_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
      RUN_AT_UTC TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
