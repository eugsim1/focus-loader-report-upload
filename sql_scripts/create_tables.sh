)
COMPRESS FOR QUERY HIGH
PARTITION BY RANGE (CHARGE_PERIOD_START)
INTERVAL (NUMTOYMINTERVAL(1,'MONTH'))
(
    PARTITION p_init VALUES LESS THAN (DATE '2025-01-01')
