	"BILLED_COST" NUMBER,
	"BILLING_CURRENCY" VARCHAR2(100) COLLATE "USING_NLS_COMP",
	"CONSUMED_QUANTITY" NUMBER,
	"CONSUMED_UNIT" VARCHAR2(1000) COLLATE "USING_NLS_COMP",
	"CONTRACTED_COST" NUMBER,
	"CONTRACTED_UNIT_PRICE" NUMBER,
	"EFFECTIVE_COST" NUMBER,
	"LIST_COST" NUMBER,
	"LIST_UNIT_PRICE" NUMBER,
	"AVAILABILITY_ZONE" VARCHAR2(1000) COLLATE "USING_NLS_COMP",
	"REGION_ID" VARCHAR2(1000) COLLATE "USING_NLS_COMP",
	"REGION_NAME" VARCHAR2(1000) COLLATE "USING_NLS_COMP",
	"RESOURCE_ID" VARCHAR2(1000) COLLATE "USING_NLS_COMP",
	"RESOURCE_NAME" VARCHAR2(1000) COLLATE "USING_NLS_COMP",
