CREATE TABLE SQLLOADER_AUDIT (
    ID                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SOURCE_TENANT_NAME  VARCHAR2(255),
    FILE_ID             VARCHAR2(512),
    FILE_NAME           VARCHAR2(1024),
    DATA_FILE           VARCHAR2(1024),
    LOG_FILE            VARCHAR2(1024),
    STATUS              VARCHAR2(30),
    ROWS_INSERTED       NUMBER,
    ROWS_FAILED         NUMBER,
    ROWS_REJECTED       NUMBER,
    ROWS_DISCARDED      NUMBER,
    ROWS_SKIPPED        NUMBER,
    TOTAL_ROWS_READ     NUMBER,
    TOTAL_FILE_LINES    NUMBER,
    FILE_SIZE_BYTES     NUMBER,
    LOADER_START_TIME   TIMESTAMP,
    LOADER_END_TIME     TIMESTAMP,
    DURATION_SECONDS    NUMBER,
    ERROR_MESSAGE       VARCHAR2(4000),
    INSERTED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX SQLLOADER_AUDIT_N1
    ON SQLLOADER_AUDIT (SOURCE_TENANT_NAME, FILE_NAME);

CREATE INDEX SQLLOADER_AUDIT_N2
    ON SQLLOADER_AUDIT (INSERTED_AT);
