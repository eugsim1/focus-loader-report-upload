#!/usr/bin/env bash

set -euo pipefail

ADMIN_USER=${1:-${ADMIN_USER:-}}
ADMIN_PASS=${2:-${ADMIN_PASS:-}}
DB_CONN=${3:-${DB_CONN:-}}
TARGET_SCHEMA=${4:-${TARGET_SCHEMA:-}}
TARGET_PASS=${5:-${TARGET_PASS:-}}
CONFIG_FILE=${6:-${CONFIG_FILE:-focus.conf}}
DROP_EXISTING=${DROP_EXISTING:-true}

if [ -z "${ADMIN_PASS:-}" ] && [ -t 0 ]; then
  read -r -s -p "Oracle admin password: " ADMIN_PASS
  echo
fi
if [ -z "${TARGET_PASS:-}" ] && [ -t 0 ]; then
  read -r -s -p "Target schema password: " TARGET_PASS
  echo
fi

if [ -z "${ADMIN_USER:-}" ] || [ -z "${ADMIN_PASS:-}" ] || [ -z "${DB_CONN:-}" ] || [ -z "${TARGET_SCHEMA:-}" ] || [ -z "${TARGET_PASS:-}" ]; then
  echo "Usage:"
  echo "$0 <admin_user> <admin_pass> <tns> <schema> <schema_pass> [config_file]"
  echo "Or set ADMIN_USER, DB_CONN, TARGET_SCHEMA, and optionally CONFIG_FILE; passwords are prompted on a terminal."
  exit 1
fi

if ! command -v sqlplus >/dev/null 2>&1; then
  echo "sqlplus not found in PATH"
  exit 1
fi

if [ ! -f "$CONFIG_FILE" ]; then
  echo "Config file not found: $CONFIG_FILE"
  exit 1
fi

if [[ ! "$TARGET_SCHEMA" =~ ^[A-Za-z][A-Za-z0-9_\$#]*$ ]]; then
  echo "Invalid schema name: $TARGET_SCHEMA"
  echo "Use an unquoted Oracle identifier: starts with a letter, then letters/numbers/_/$/#"
  exit 1
fi

case "$(printf '%s' "$DROP_EXISTING" | tr '[:upper:]' '[:lower:]')" in
  true|yes|1|false|no|0) ;;
  *)
    echo "Invalid DROP_EXISTING value: $DROP_EXISTING"
    echo "Use true/false, yes/no, or 1/0"
    exit 1
    ;;
esac

SCHEMA=$(printf '%s' "$TARGET_SCHEMA" | tr '[:lower:]' '[:upper:]')
TARGET_PASS_SQL=${TARGET_PASS//\"/\"\"}

T_FOCUS=TEMP_OCI_FOCUS
T_TAGS=TEMP_OCI_FOCUS_TAGS
T_TAG_KEYS=TEMP_OCI_FOCUS_TAG_KEYS
T_STATS=TEMP_OCI_FOCUS_STATS
T_LOAD=TEMP_OCI_FOCUS_LOAD_STATUS
T_REF=TEMP_OCI_FOCUS_REFERENCE
T_SQLLOADER_AUDIT=SQLLOADER_AUDIT

FQN_FOCUS=${SCHEMA}.${T_FOCUS}
FQN_TAGS=${SCHEMA}.${T_TAGS}
FQN_TAG_KEYS=${SCHEMA}.${T_TAG_KEYS}
FQN_STATS=${SCHEMA}.${T_STATS}
FQN_LOAD=${SCHEMA}.${T_LOAD}
FQN_REF=${SCHEMA}.${T_REF}
FQN_SQLLOADER_AUDIT=${SCHEMA}.${T_SQLLOADER_AUDIT}

sqlplus "${ADMIN_USER}/${ADMIN_PASS}@${DB_CONN}" <<EOF

WHENEVER OSERROR EXIT 9
WHENEVER SQLERROR EXIT SQL.SQLCODE

SET SERVEROUTPUT ON
SET FEEDBACK ON
SET ECHO OFF

PROMPT ============================================
PROMPT STARTING SCHEMA DEPLOYMENT
PROMPT ============================================

PROMPT ---- Preparing target schema owner ----

DECLARE
  v_count NUMBER;
  v_drop_existing VARCHAR2(10) := LOWER('${DROP_EXISTING}');
BEGIN
  SELECT COUNT(*) INTO v_count
  FROM all_users
  WHERE username = UPPER('${SCHEMA}');

  IF v_count > 0 THEN
    IF v_drop_existing IN ('true', 'yes', '1') THEN
      EXECUTE IMMEDIATE 'DROP USER ${SCHEMA} CASCADE';
      DBMS_OUTPUT.PUT_LINE('Existing user dropped');
      v_count := 0;
    ELSE
      EXECUTE IMMEDIATE 'ALTER USER ${SCHEMA} IDENTIFIED BY "${TARGET_PASS_SQL}"';
      DBMS_OUTPUT.PUT_LINE('Existing user retained and password updated');
    END IF;
  END IF;

  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'CREATE USER ${SCHEMA} IDENTIFIED BY "${TARGET_PASS_SQL}"';
    DBMS_OUTPUT.PUT_LINE('User created');
  END IF;
END;
/

DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count
  FROM all_users
  WHERE username = UPPER('${SCHEMA}');

  IF v_count = 0 THEN
    RAISE_APPLICATION_ERROR(-20001, 'Target schema was not created: ${SCHEMA}');
  ELSE
    DBMS_OUTPUT.PUT_LINE('Verified target schema owner: ${SCHEMA}');
  END IF;
END;
/
PROMPT ---- Granting privileges ----

GRANT CONNECT, DWROLE TO ${SCHEMA};
GRANT CREATE TABLE, CREATE VIEW, CREATE PROCEDURE TO ${SCHEMA};
GRANT UNLIMITED TABLESPACE TO ${SCHEMA};



PROMPT ---- Switching to schema ${SCHEMA} ----
ALTER SESSION SET CURRENT_SCHEMA=${SCHEMA};



PROMPT ---- Creating main table ----


-- =====================================
-- Create main table
-- =====================================
