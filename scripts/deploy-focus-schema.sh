import configparser
import sys
from pathlib import Path

config_file = Path(sys.argv[1])
schema = sys.argv[2]
focus, tags, tag_keys, stats, load_status, reference, sqlloader_audit = sys.argv[3:10]

parser = configparser.ConfigParser(strict=False)
parser.optionxform = str
parser.read(config_file)

if not parser.has_section("database"):
    parser.add_section("database")
parser.set("database", "schema", schema)

if not parser.has_section("tables"):
    parser.add_section("tables")

table_values = {
    "FOCUS": focus,
    "TAGS": tags,
    "FOCUS_TAGS": tags,
    "TAG_KEYS": tag_keys,
    "TAG_KEYS_REF": tag_keys,
    "STATS": stats,
    "LOAD_STATUS": load_status,
    "REFERENCE": reference,
    "SQLLOADER_AUDIT": sqlloader_audit,
}

for key, value in table_values.items():
    parser.set("tables", key, value)

with config_file.open("w", encoding="utf-8") as handle:
    parser.write(handle)
PY
